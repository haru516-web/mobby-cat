# Resize cat PNGs to 512px for the app and generate app/src/data/catalog.ts from manifest.json
Add-Type -AssemblyName System.Drawing
$root = Split-Path $PSScriptRoot -Parent
$m = Get-Content "$root\assets\cat-mobbies\manifest.json" -Raw -Encoding UTF8 | ConvertFrom-Json
$outDir = "$root\app\assets\cats"
New-Item -ItemType Directory -Force $outDir | Out-Null
New-Item -ItemType Directory -Force "$root\app\src\data" | Out-Null

# rarity: 1=common 2=uncommon 3=rare 4=legend
$rarity = @{
  'british-shorthair'=1;'american-shorthair'=1;'scottish-fold'=1;'persian'=1;'russian-blue'=1;'siamese-seal-point'=1;'exotic-shorthair'=1;'ragdoll'=1;'birman'=1;'japanese-bobtail'=1;'abyssinian'=1;'maine-coon'=1;
  'norwegian-forest'=2;'balinese'=2;'somali'=2;'turkish-angora'=2;'siberian'=2;'tonkinese'=2;'ragamuffin'=2;'american-curl'=2;'manx'=2;'burmese'=2;'snowshoe'=2;
  'bengal'=3;'turkish-van'=3;'selkirk-rex'=3;'devon-rex'=3;'cornish-rex'=3;'egyptian-mau'=3;'ocicat'=3;'singapura'=3;'havana-brown'=3;
  'toyger'=4;'bombay'=4;
  'rea-mobby'=3;'uyu-mobby'=2
}

$lines = @("// generated by tools/build-app-assets.ps1 - do not edit", "export type Rarity = 1 | 2 | 3 | 4;", "export type CatDef = { id: string; name: string; rarity: Rarity; image: number };", "", "export const CATS: CatDef[] = [")
foreach ($c in $m.characters) {
  $src = "$root\assets\cat-mobbies\$($c.file)"
  $dst = "$outDir\$($c.id).png"
  $img = [System.Drawing.Image]::FromFile($src)
  $bmp = New-Object System.Drawing.Bitmap 512, 512
  $g = [System.Drawing.Graphics]::FromImage($bmp)
  $g.InterpolationMode = 'HighQualityBicubic'
  $g.DrawImage($img, 0, 0, 512, 512)
  $bmp.Save($dst, [System.Drawing.Imaging.ImageFormat]::Png)
  $g.Dispose(); $bmp.Dispose(); $img.Dispose()
  $r = if ($rarity.ContainsKey($c.id)) { $rarity[$c.id] } else { 2 }
  $lines += "  { id: '$($c.id)', name: '$($c.name)', rarity: $r, image: require('../../assets/cats/$($c.id).png') },"
}
$lines += "];"
[System.IO.File]::WriteAllText("$root\app\src\data\catalog.ts", ($lines -join "`n") + "`n", (New-Object System.Text.UTF8Encoding($false)))
"done: $($m.characters.Count)"
