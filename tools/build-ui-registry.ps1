# Generate app/src/ui/uiAssets.ts from the PNGs in app/assets/ui (re-run after adding/replacing assets)
# 9-slice insets come from app/assets/ui/manifest.json ("slice": top/right/bottom/left in source px)
Add-Type -AssemblyName System.Drawing
$root = Split-Path $PSScriptRoot -Parent
$base = "$root\app\assets\ui"
$skip = @('previews', 'provenance', 'guides')
$slices = @{}
$regions = @{}
$manifest = Get-Content "$base\manifest.json" -Raw -Encoding UTF8 | ConvertFrom-Json
foreach ($a in $manifest.assets) {
  if ($a.slice) { $slices[$a.path] = $a.slice }
  if ($a.regions) { $regions[$a.path] = $a.regions }
}
$lines = @(
  "// generated by tools/build-ui-registry.ps1 - do not edit",
  "export type UISlice = { t: number; r: number; b: number; l: number };",
  "export type UIRect = { x: number; y: number; w: number; h: number };",
  "export type UIAsset = { src: number; w: number; h: number; slice?: UISlice; regions?: Record<string, UIRect> };",
  "",
  "export const UI: Record<string, UIAsset | undefined> = {"
)
Get-ChildItem $base -Recurse -Filter *.png | Sort-Object FullName | ForEach-Object {
  $rel = $_.FullName.Substring($base.Length + 1).Replace('\', '/')
  if ($skip -contains $rel.Split('/')[0]) { return }
  $img = [System.Drawing.Image]::FromFile($_.FullName)
  $w = $img.Width; $h = $img.Height
  $img.Dispose()
  $key = $rel.Substring(0, $rel.Length - 4)
  $sl = ''
  if ($slices.ContainsKey($rel)) {
    $s = $slices[$rel]
    $sl = ", slice: { t: $($s.top), r: $($s.right), b: $($s.bottom), l: $($s.left) }"
  }
  if ($regions.ContainsKey($rel)) {
    $parts = $regions[$rel].PSObject.Properties | ForEach-Object { "$($_.Name): { x: $($_.Value.x), y: $($_.Value.y), w: $($_.Value.w), h: $($_.Value.h) }" }
    $sl += ", regions: { $($parts -join ', ') }"
  }
  $lines += "  '$key': { src: require('../../assets/ui/$rel'), w: $w, h: $h$sl },"
}
$lines += "};"
New-Item -ItemType Directory -Force "$root\app\src\ui" | Out-Null
[System.IO.File]::WriteAllText("$root\app\src\ui\uiAssets.ts", ($lines -join "`n") + "`n", (New-Object System.Text.UTF8Encoding($false)))
"entries: $($lines.Count - 6), sliced: $($slices.Count)"
